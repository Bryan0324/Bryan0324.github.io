import assert from 'node:assert/strict';
import { existsSync, readFileSync, readdirSync, statSync } from 'node:fs';
import { resolve, relative } from 'node:path';
import matter from 'gray-matter';
import { site } from '../src/lib/config.mjs';
import { href, localDate, postPath } from '../src/lib/urls.mjs';

const output = resolve('dist');
assert.ok(existsSync(output), 'Run npm run build first');
const files = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((entry) => entry.isDirectory() ? files(resolve(dir, entry.name)) : [resolve(dir, entry.name)]);
const htmlFiles = files(output).filter((file) => file.endsWith('.html'));
let posts = 0;
const articles = new Map();
const visibleUrls = [];
for (const file of files(resolve('source/_posts')).filter((file) => /\.mdx?$/.test(file))) {
  const { data, content } = matter(readFileSync(file, 'utf8'));
  if ((!data.title && !content.trim()) || data.draft) continue;
  if (site.future === false && localDate(data.date, site.timezone).valueOf() > Date.now()) continue;
  const id = relative(resolve('source/_posts'), file).replaceAll('\\', '/').replace(/\/index\.mdx?$|\.mdx?$/, '');
  const path = postPath(id, data, site);
  const target = path.endsWith('.html') ? resolve(output, path) : resolve(output, path, 'index.html');
  assert.ok(existsSync(target), `Missing article: ${id} (${path})`);
  const html = readFileSync(target, 'utf8');
  articles.set(id, html);
  if (!data.hide) visibleUrls.push(href(path));
  assert.ok(html.includes('class="post-content markdown-body"'), `Missing article body: ${id}`);
  assert.ok(html.includes('name="generator" content="Astro'), `Not generated by Astro: ${id}`);
  posts++;
}
const missing = new Set();
for (const file of htmlFiles) {
  const html = readFileSync(file, 'utf8');
  for (const match of html.matchAll(/<(?:a|img|script|link|source|video)\b[^>]*\b(?:href|src)="(\/[^" ]*)"/g)) {
    if (match[1].startsWith('//')) continue;
    const path = decodeURIComponent(match[1]).split(/[?#]/)[0];
    const target = resolve(output, `.${path}`);
    if (!existsSync(target) || (statSync(target).isDirectory() && !existsSync(resolve(target, 'index.html')))) missing.add(`${relative(output, file)} → ${path}`);
  }
}
assert.deepEqual([...missing], [], 'Broken local links or assets');
const index = JSON.parse(readFileSync(resolve(output, 'search.json'), 'utf8'));
assert.deepEqual(index.map((entry) => entry.url).sort(), visibleUrls.sort(), 'Search must follow configured permalinks and publication filters');
const graph = articles.get('8-CP-tarjan');
if (graph) assert.match(graph, /<astro-island[^>]+client="visible"/, 'React graph is not hydrated');
const math = articles.get('9-CP-inversion-number');
if (math) assert.ok(math.includes('class="katex"'), 'Math was not rendered');
assert.ok(existsSync(resolve(output, '404.html')), 'Missing GitHub Pages 404');
assert.ok(statSync(resolve(output, 'about/site.html')).isFile(), 'Legacy HTML page must not redirect to a directory');
assert.ok(existsSync(resolve(output, 'CNAME')), 'Missing custom domain');
console.log(`Verified ${posts} articles, ${htmlFiles.length} HTML pages, search, React hydration, math and all local links/assets.`);
